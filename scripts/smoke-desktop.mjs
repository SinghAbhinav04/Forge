import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const output = path.resolve('test-artifacts'); await fs.mkdir(output, { recursive: true });
const testRoot = await fs.mkdtemp(path.join(output, 'desktop-'));
const launchEnv = { ...process.env, LOCAL_DESK_TEST_ROOT: testRoot }; delete launchEnv.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ['.'], env: launchEnv, timeout: 60000 });
const errors = [];
try {
  const page = await app.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  await page.waitForSelector('#hardware-label:text("GB RAM")');
  await page.screenshot({ path: path.join(output, 'workspace.png') });
  await page.getByRole('button', { name: 'Models', exact: false }).first().click();
  await page.waitForSelector('.model-card');
  assert.ok(await page.locator('.model-card').count());
  await page.screenshot({ path: path.join(output, 'models.png') });
  await page.locator('[data-view="settings"]').click();
  await page.locator('[data-panel="defaults"]').click();
  await page.waitForSelector('#setting-contextSize');
  assert.ok(Number(await page.locator('#setting-contextSize').inputValue()) >= 512);
  await page.locator('[data-view="workspace"]').click();
  await page.getByRole('button', { name: 'Welcome.md', exact: false }).click();
  await page.waitForFunction(() => document.getElementById('editor').value.includes('Your local workspace'));
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await page.locator('#document-preview h1').waitFor();
  await page.screenshot({ path: path.join(output, 'document.png') });
  await page.getByRole('button', { name: 'New document', exact: true }).click();
  const name = `Smoke-${Date.now()}.md`;
  await page.locator('#path-input').fill(name);
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.locator('#editor').fill('# Verified\n\nSaved through the desktop editor.');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('editor-status').textContent === 'Saved on this device');
  assert.ok((await fs.readFile(path.join(testRoot, 'workspace', name), 'utf8')).includes('Saved through the desktop editor.'));
  await fs.unlink(path.join(testRoot, 'workspace', name));
  await page.locator('#refresh-files').click();
  await page.setViewportSize({ width: 1080, height: 760 });
  await page.screenshot({ path: path.join(output, 'compact.png') });
  if (process.argv.includes('--inference')) {
    await page.setViewportSize({ width: 1434, height: 921 });
    await page.locator('[data-view="settings"]').click();
    await page.locator('[data-panel="defaults"]').click();
    await page.locator('#setting-contextSize').fill('2048');
    await page.locator('#setting-maxTokens').fill('512');
    await page.locator('#setting-gpuLayers').fill('24');
    await page.locator('#setting-threads').fill('2');
    await page.locator('#setting-temperature').fill('0');
    await page.getByRole('button', { name: 'Save settings', exact: true }).click();
    await page.waitForFunction(() => document.getElementById('settings-saved').textContent.startsWith('Saved.'));
    await page.locator('[data-panel="runtime"]').click();
    await page.locator('#runtime-form [data-setting="kvOnGpu"]').check();
    await page.locator('#runtime-form [data-setting="executionMode"]').selectOption('gpu');
    await page.locator('#runtime-form [data-setting="loadStrategy"]').selectOption('stream');
    await Promise.all([page.waitForResponse(r => new URL(r.url()).pathname==='/api/settings' && r.ok()),page.getByRole('button',{ name:'Save runtime settings',exact:true }).click()]);
    await page.locator('[data-view="models"]').click();
    await page.evaluate(() => { window.__loadTiming={ started:performance.now(),last:performance.now(),maxGap:0,samples:0 }; window.__loadTimer=setInterval(() => { const now=performance.now(); window.__loadTiming.maxGap=Math.max(window.__loadTiming.maxGap,now-window.__loadTiming.last); window.__loadTiming.last=now; window.__loadTiming.samples++; },20); });
    const [loadResponse]=await Promise.all([page.waitForResponse(r => new URL(r.url()).pathname==='/api/model/load'),page.getByRole('button',{ name:'Load model',exact:true }).first().click()]);
    if (!loadResponse.ok()) throw new Error((await loadResponse.json()).error);
    await page.waitForFunction(() => ['Model ready','Runtime needs attention'].includes(document.getElementById('library-runtime-status').textContent),null,{ timeout:120000 });
    if ((await page.locator('#library-runtime-status').textContent())!=='Model ready') { const diagnostic=await page.evaluate(async () => (await fetch('/api/runtime',{ headers:{ 'X-Local-Desk-Token':sessionStorage.getItem('local-desk-token') } })).json()); await fs.writeFile(path.join(output,'load-failure.json'),JSON.stringify(diagnostic,null,2)); throw new Error(await page.locator('#library-runtime-detail').textContent()); }
    const latency=await page.evaluate(() => { clearInterval(window.__loadTimer); return { ...window.__loadTiming,duration:performance.now()-window.__loadTiming.started }; });
    await fs.writeFile(path.join(output,'loading-responsiveness.json'),JSON.stringify(latency,null,2));
    assert.ok(latency.maxGap<1500,`UI stalled for ${latency.maxGap.toFixed(0)}ms during load`);
    console.log(`Loading UI responsiveness: maximum timer gap ${latency.maxGap.toFixed(1)}ms over ${(latency.duration/1000).toFixed(1)}s.`);
    await page.locator('[data-view="settings"]').click();
    await page.locator('[data-panel="skills"]').click();
    await page.locator('#skill-name').fill('Verification style');
    await page.locator('#skill-instructions').fill('For this verification, start every final assistant answer with FORGE_SKILL_OK. Use requested tools normally. Do not put this marker inside files you write.');
    await page.locator('#skill-enabled').check();
    await page.locator('#skill-form button.primary-button').click();
    await page.locator('#skill-list').getByText('Verification style',{ exact:true }).waitFor();
    await page.locator('[data-view="workspace"]').click();
    await page.locator('#new-session').click();
    await page.locator('#prompt').fill('Call write_file to create UiSmoke.md. Set the content to a Markdown heading saying Desktop test, then a sentence saying This document was created through the workspace agent.');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('.approval') || (document.getElementById('stop-task').hidden && !document.getElementById('task-notice').hidden),null,{ timeout:240000 });
    if (!(await page.getByRole('button',{ name:'Apply write',exact:true }).isVisible())) throw new Error(await page.locator('#task-notice').textContent());
    await page.screenshot({ path: path.join(output, 'approval.png') });
    await page.getByRole('button', { name: 'Apply write', exact: true }).click();
    await page.waitForFunction(() => document.getElementById('stop-task').hidden, null, { timeout: 240000 });
    const contents = await fs.readFile(path.join(testRoot, 'workspace', 'UiSmoke.md'), 'utf8');
    assert.ok(contents.includes('Desktop test'));
    assert.ok((await page.locator('.message.assistant .message-body').last().textContent()).includes('FORGE_SKILL_OK'),'Actual model did not follow the enabled skill');
    if (await page.locator('#task-notice').isVisible()) assert.ok(!(await page.locator('#task-notice').textContent()).includes('failed'));
    await page.locator('#file-list .file-row').filter({ hasText: 'UiSmoke.md' }).click();
    await page.getByRole('button', { name: 'Preview', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'agent-workspace.png') });
    console.log('Actual-model desktop flow passed: GGUF loading, streamed tool call, approval card, file write, and preview.');
  }
  assert.deepEqual(errors, []);
  console.log('Desktop smoke passed: navigation, model discovery, Markdown preview, and saving a document.');
  console.log(`Screenshots: ${output}`);
} finally { await app.close(); }
